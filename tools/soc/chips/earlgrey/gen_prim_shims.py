#!/usr/bin/env python3
"""Write one wrapper module prim_<x> per hw/ip/prim_generic/rtl/prim_generic_<x>.sv.

OpenTitan's abstract primitives (prim_flop, prim_buf, prim_ram_1p, ...) are generated by FuseSoC's primgen at
build time and are not in the repository. Each wrapper written here has the header of the generic module (copied
textually, module name changed) and instantiates the generic implementation with every parameter passed on and
ports connected by name. Own code, Apache-2.0.

Usage: gen_prim_shims.py <opentitan checkout> <output .sv> [more prim_generic dirs]
"""
import glob
import os
import re
import sys


def shim(path):
    text = open(path).read()
    name = os.path.basename(path)[len('prim_generic_'):-3]
    m = re.search(r'^module\s+prim_generic_%s\b' % re.escape(name), text, re.M)
    if not m:
        return None
    # header ends at the first ");" at nesting depth 0 after the module keyword
    depth = 0
    i = m.end()
    end = None
    while i < len(text):
        ch = text[i]
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
            if depth == 0 and text[i + 1:i + 40].lstrip().startswith(';'):
                end = text.index(';', i) + 1
                break
        i += 1
    if end is None:
        return None
    header = text[m.start():end].replace('prim_generic_' + name, 'prim_' + name, 1)
    plist = header.split(')', 1)[0] if '#' in header.split('(', 1)[0] + header[:header.find('(') + 1] else ''
    params = []
    hm = re.search(r'#\s*\(', header)
    if hm:
        d = 0
        j = hm.end() - 1
        while j < len(header):
            if header[j] == '(':
                d += 1
            elif header[j] == ')':
                d -= 1
                if d == 0:
                    break
            j += 1
        pblock = re.sub(r'/\*.*?\*/', '', re.sub(r'//[^\n]*', '', header[hm.end():j]), flags=re.S)
        for part in re.split(r',(?![^\[\(\{]*[\]\)\}])', pblock):
            part = part.strip()
            if not part or part.startswith('localparam'):
                continue
            mm = re.match(r'(?:parameter\s+)?(?:[\w:]+\s+)*?(?:\[[^\]]*\]\s*)*(\w+)\s*(?:\[[^\]]*\]\s*)*=', part, re.S)
            if mm:
                params.append(mm.group(1))
    pre = text[:m.start()]
    includes = '\n'.join(l for l in pre.split('\n') if l.strip().startswith('`include'))
    inst = '  prim_generic_%s' % name
    if params:
        inst += ' #(\n' + ',\n'.join('    .%s(%s)' % (p, p) for p in params) + '\n  )'
    inst += ' u_impl_generic (.*);\n'
    return '%s\n%s\n%sendmodule\n' % (includes, header, inst)


def main():
    root, out = sys.argv[1], sys.argv[2]
    dirs = [os.path.join(root, 'hw/ip/prim_generic/rtl')] + sys.argv[3:]
    parts = ['// Generated by gen_prim_shims.py: wrappers that select the generic implementation of each abstract\n'
             '// primitive. Do not edit.\n',
             '// prim_pkg is generated by primgen as well; only the implementation selector is needed.\n'
             'package prim_pkg;\n  typedef enum integer {ImplGeneric, ImplXilinx, ImplXilinx_ultrascale, ImplBadbit} impl_e;\n'
             'endpackage : prim_pkg\n']
    names = []
    for d in dirs:
        for p in sorted(glob.glob(os.path.join(d, 'prim_generic_*.sv'))):
            s = shim(p)
            if s:
                parts.append(s)
                names.append(os.path.basename(p)[13:-3])
    with open(out, 'w') as f:
        f.write('\n'.join(parts))
    print('%d wrappers: %s' % (len(names), ' '.join(names)))


if __name__ == '__main__':
    main()
