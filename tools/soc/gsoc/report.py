"""Collect results/runs/*.json into: results/soc_results.json (everything, one file), results/RESULTS.md (tables),
studio/explore_chip.json (the guided "Explore a real chip" view: what the chip is, where its security decisions
live, what was found). Every number is copied from a run file; nothing is computed here except sums and shares."""
import glob
import json
import os

from . import SOC, run

FLOW_PLAIN = {
    'written': 'as written: turned into gates with no optimisation',
    'keep': 'synthesised, protected blocks kept apart',
    'flat': 'synthesised, everything optimised together',
}
LABEL_PLAIN = {
    'BOUNDED': 'BOUNDED (within T cycles): the exact smallest number within the stated number of clock cycles after reset. An attack of this size was replayed on the whole chip, and the solver showed that no smaller one exists in the model within those cycles. It says nothing about longer runs, so it is not called proved',
    'PARTIAL': 'PARTIAL: only a range is known within the stated number of cycles (time limit or fault budget reached)',
    'SAMPLED': 'SAMPLED: a simulation campaign; it reports what happened in the scenarios that were run',
}


def relabel(r):
    """Labels of run files written before the audit: PROVED (exact within T) is BOUNDED, BOUNDED (a range) is PARTIAL."""
    if r.get('schema', '').startswith('glitchsat-soc-goal') and r.get('label') in ('PROVED', 'BOUNDED') and not r.get('relabelled'):
        r['label'] = 'BOUNDED' if r.get('status') == 'EXACT' else 'PARTIAL'
        r['relabelled'] = True
    return r


def _runs():
    out = dict(chip={}, goal={}, campaign={}, inventory={})
    for p in sorted(glob.glob(os.path.join(run.RUNS, '*.json'))):
        r = relabel(run._load(p))
        s = r.get('schema', '')
        if s.startswith('glitchsat-soc-chip'):
            out['chip'][(r['chip'], r['variant'], r['flow'])] = r
        elif s.startswith('glitchsat-soc-goal'):
            out['goal'][(r['chip'], r['variant'], r['flow'], r['goal'])] = r
        elif s.startswith('glitchsat-soc-campaign'):
            out['campaign'][(r['chip'], r['variant'], r['flow'], r['goal'])] = r
        elif s.startswith('glitchsat-soc-inventory'):
            out['inventory'][(r['chip'], r['variant'])] = r
    return out


def _answer(g):
    if g['label'] == 'BOUNDED':
        return '%d' % g['min_faults']
    if g['status'] == 'NO_ATTACK_UP_TO_BOUND':
        return '> %d' % g['spec']['kmax']
    if g['hi'] is not None:
        return '%d..%d' % (g['lo'], g['hi'])
    return '>= %d' % g['lo']


def _plain_findings():
    """The shared plain-words explainer (tools/findings in the repository, ext/findings in a work tree), or None."""
    import importlib.util
    for d in (os.environ.get('GLITCHSAT_FINDINGS'), os.path.join(os.path.dirname(SOC), 'findings')):
        p = os.path.join(d or '', 'plain_findings.py')
        if d and os.path.isfile(p):
            sp = importlib.util.spec_from_file_location('plain_findings', p)
            m = importlib.util.module_from_spec(sp)
            sp.loader.exec_module(m)
            return m
    return None


def _attempts():
    p = os.path.join(SOC, 'results', 'opentitan_attempt.json')
    return run._load(p) if os.path.exists(p) else None


def write_all():
    R = _runs()
    chips = sorted({k[0] for k in R['chip']})
    allres = dict(schema='glitchsat-soc-results/1', labels=LABEL_PLAIN, chips=[], opentitan=_attempts())
    L = ['# Whole-chip results', '',
         'Generated by `glitchsat_soc.py report` from `results/runs/*.json`. Every number is MEASURED in the build',
         'environment (2 cores, about 7 GB RAM) unless a row says otherwise. Fault model: single-cycle bit flips on',
         'cell outputs. BOUNDED (exact within T cycles) / PARTIAL / SAMPLED are defined in the README, section 5. No result',
         'here is an unbounded proof.', '']
    studio = dict(schema='glitchsat-studio-explore-chip/1',
                  intro=dict(
                      title='Explore a real chip',
                      plain=['So far every design in this app was one small block. A real chip is tens of thousands of '
                             'gates: a processor, memory, a serial port, and somewhere inside it a handful of wires that '
                             'decide security questions such as "may this chip start?" or "may a debugger take over?".',
                             'Here the same question is asked about whole open-source chips: how many momentary bit flips '
                             'does an attacker need to turn one of those decisions around?',
                             'Three kinds of answer appear, and they are not the same thing.'],
                      labels=LABEL_PLAIN,
                      limits=['A bit flip in a netlist is a model of a fault, not a measurement on silicon.',
                              'Every answer covers a stated number of clock cycles after reset, not all time.',
                              'Large memories are black boxes: the analysis allows any content.',
                              'The chips were built with an open synthesis flow without a cell library; a production '
                              'flow gives a different netlist and may give different numbers.']),
                  chips=[])
    for name in chips:
        cfg = run.load_cfg(name)
        entry = dict(name=name, title=cfg.get('title'), what=' '.join(str(cfg.get('what', '')).split()), source=cfg.get('source'),
                     variants=[])
        sc = dict(id=name, title=cfg.get('title'), what_this_chip_is=entry['what'],
                  source='%s at commit %s (%s)' % (cfg['source']['repo'], cfg['source']['commit'][:12], cfg['source']['licence']),
                  where_security_decisions_live=[], what_we_found=[], variants=[])
        L += ['## %s' % cfg.get('title'), '', entry['what'], '',
              'Source: %s, commit `%s`, licence %s.' % (cfg['source']['repo'], cfg['source']['commit'], cfg['source']['licence']), '']
        rows_chip, rows_goal, rows_camp = [], [], []
        seen_goal = set()
        for (c, v, fl), ch in sorted(R['chip'].items()):
            if c != name:
                continue
            st = ch['stats']
            rows_chip.append('| %s | %s | %d | %d | %d | %d | %s | %s | %s |' % (
                v, fl, st['cells'], st['gates'], st['flops'], len(st['clock_domains']),
                ('%d (%d bits)' % (len([b for b in st['blackboxes'].values() if b['type'] == '$mem_v2']), st['memory_bits_blackboxed'])) if st['memory_bits_blackboxed'] else '0',
                '%d / %d' % (ch['reset'].get('flops_known', 0), ch['reset'].get('flops_unknown', 0)),
                ('%.0f s' % ch['frontend']['seconds']) if ch['frontend'].get('seconds') else 'n/a'))
            var = dict(variant=v, flow=fl, flow_plain=FLOW_PLAIN.get(fl, fl), stats=st, reset=ch['reset'], frontend=ch['frontend'], goals=[], campaigns=[])
            vt = (cfg.get('variants') or {}).get(v, {}).get('title', v)
            vnote = (cfg.get('variants') or {}).get(v, {}).get('note')
            sv = dict(variant=v, variant_plain=vt, note=' '.join(str(vnote).split()) if vnote else None, flow=fl,
                      flow_plain=FLOW_PLAIN.get(fl, fl), cells=st['cells'], gates=st['gates'],
                      flops=st['flops'], goals=[])
            for (c2, v2, f2, gid), g in sorted(R['goal'].items()):
                if (c2, v2, f2) != (c, v, fl):
                    continue
                sl = g['slice']
                rows_goal.append('| %s | %s | %s | %d | %d | %.2f %% | **%s** | %s | %.1f s |' % (
                    v, fl, gid, g['spec']['cycles'], sl['slice_cells'], 100 * sl['slice_share'], _answer(g), g['label'],
                    g['search']['seconds']))
                var['goals'].append(g)
                w = g.get('witness')
                sv['goals'].append(dict(
                    id=gid, title=g['title'], faults_needed=_answer(g), label=g['label'], cycles=g['spec']['cycles'],
                    slice_cells=sl['slice_cells'], slice_percent=round(100 * sl['slice_share'], 2), seconds=g['search']['seconds'],
                    example=[dict(net=f['net'], cycle=f['cycle'], kind=f['kind']) for f in (w or {}).get('faults', [])],
                    example_note=(w or {}).get('note'), cone_growth=g['cone_growth']))
                if gid not in seen_goal:
                    seen_goal.add(gid)
                    sc['where_security_decisions_live'].append(dict(goal=gid, title=g['title'], plain=' '.join(str(g['plain']).split()),
                                                                    where=g['where']))
            for (c2, v2, f2, gid), cp in sorted(R['campaign'].items()):
                if (c2, v2, f2) != (c, v, fl):
                    continue
                rows_camp.append('| %s | %s | %s | %d / %d | %d / %d (%s) | %d cells | %d / %d | %.0f s |' % (
                    v, fl, gid, cp['no_fault']['goal_reached'], cp['no_fault']['scenarios'], cp['single']['goal_reached'],
                    cp['single']['scenarios'], 'every cell x cycle' if cp['single']['complete_fault_space'] else 'partial',
                    cp['single']['distinct_cells'], cp['pairs']['goal_reached'], cp['pairs']['scenarios'], cp['seconds']))
                var['campaigns'].append(cp)
            entry['variants'].append(var)
            sc['variants'].append(sv)
        L += ['### Chip size and front end', '',
              '| variant | flow | cells | gates | flops | clock domains | memories kept as black boxes | flops known / unknown after reset | synthesis |',
              '|---|---|---|---|---|---|---|---|---|'] + rows_chip + ['']
        L += ['### Minimum faults per security goal', '',
              '| variant | flow | goal | cycles T | slice (cells) | slice / chip | faults needed | label | search time |',
              '|---|---|---|---|---|---|---|---|---|'] + rows_goal + ['']
        if rows_camp:
            L += ['### Whole-chip fault campaigns (SAMPLED)', '',
                  '| variant | flow | goal | no fault: goal reached | one fault: goal reached | distinct cells | two random faults | time |',
                  '|---|---|---|---|---|---|---|---|'] + rows_camp + ['']
        inv_rows = []
        for (c, v), inv in sorted(R['inventory'].items()):
            if c != name:
                continue
            rs = inv['rtl_scan']
            vd = rs['verdicts']
            ns = '; '.join('%s: %d' % (fl, s['found']) for fl, s in inv['netlist_scan'].items())
            ml = '; '.join('%s/%s: %s' % (g, fl, x.get('verdict')) for g, d in inv['merge_lint'].items() for fl, x in d.items()) or 'n/a'
            inv_rows.append('| %s | %d | %d | %d | %d | %d | %d | %s | %s |' % (
                v, rs['found'], inv.get('reviewed', 0), vd.get('SURVIVED', 0), vd.get('WEAKENED', 0), vd.get('REMOVED', 0),
                vd.get('UNTRACKED', 0), ns, ml))
            entry.setdefault('inventory', {})[v] = inv
            sc.setdefault('inventory', []).append(dict(
                variant=v, found=rs['found'], verdicts=vd, flows=inv['flows'],
                reviewed=[dict(title=x['title'], verdict=x['verdict'], note=x['reviewed'],
                               per_flow={s['stage']: s['verdict'] for s in x['stages']}) for x in rs['items'] if x.get('reviewed')],
                unreviewed_candidates=rs['found'] - inv.get('reviewed', 0),
                merge_lint={g: {fl: x.get('verdict') for fl, x in d.items()} for g, d in inv['merge_lint'].items()}))
        if inv_rows:
            L += ['### Countermeasure inventory and survival (whole chip)', '',
                  '| variant | declared in RTL (scan) | reviewed by hand | SURVIVED | WEAKENED | REMOVED | UNTRACKED | found by structure, per flow | merge lint (goal/flow) |',
                  '|---|---|---|---|---|---|---|---|---|'] + inv_rows + ['',
                  'Verdicts are the worst verdict over the flows. Entries not reviewed by hand are candidates of the scan '
                  'heuristics; see the README, section 6.', '']
        sc['what_we_found'] = _findings(name, R)
        sc['read_with_care'] = [' '.join(str(x).split()) for x in cfg.get('caveats') or []]
        entry['caveats'] = sc['read_with_care']
        L += ['### What this says, in plain words', ''] + ['- ' + x for x in sc['what_we_found']] + ['']
        if sc['read_with_care']:
            L += ['### Read with care', ''] + ['- ' + x for x in sc['read_with_care']] + ['']
        allres['chips'].append(entry)
        studio['chips'].append(sc)
    ot = allres['opentitan']
    if ot:
        L += ['## OpenTitan (Earl Grey, English Breakfast): front-end attempt', '',
              '| step | result | wall time | peak memory | output |', '|---|---|---|---|---|']
        for s in ot['steps']:
            L.append('| %s | %s | %s | %s | %s |' % (s['step'], s['result'], s.get('wall', ''), s.get('peak_memory', ''), s.get('output', '')))
        L += ['', ot['stopped'], '', 'No fault analysis was run on OpenTitan tops; `cloud/run_opentitan.sh` is the prepared continuation. '
              'Label for everything OpenTitan-top related beyond this table: NOT RUN.', '']
        studio['next_rung'] = dict(title='OpenTitan Earl Grey: how far the front end got here', steps=ot['steps'], stopped=ot['stopped'],
                                   summary='Read in full; the gate step needs a bigger machine.',
                                   label='MEASURED for the steps listed; fault analysis NOT RUN')
    os.makedirs(os.path.join(SOC, 'results'), exist_ok=True)
    os.makedirs(os.path.join(SOC, 'studio'), exist_ok=True)
    run._save(os.path.join(SOC, 'results', 'soc_results.json'), allres)
    run._save(os.path.join(SOC, 'studio', 'explore_chip.json'), studio)
    pf = _plain_findings()
    if pf:                                     # plain words, severity and how it was found, for every chip
        L += ['## What we found and what it means (plain words)', '']
        for c in studio['chips']:
            L += ['### ' + c['title'], '', '```'] + pf.to_text(pf.from_soc_chip(c)).splitlines() + ['```', '']
    with open(os.path.join(SOC, 'results', 'RESULTS.md'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote results/soc_results.json, results/RESULTS.md, studio/explore_chip.json (%d chips)' % len(chips))


def _findings(name, R):
    """Plain sentences built from the run files of one chip."""
    out = []
    G = {k: v for k, v in R['goal'].items() if k[0] == name}
    by_goal = {}
    for (c, v, fl, gid), g in sorted(G.items()):
        by_goal.setdefault((v, gid), []).append((fl, g))
    for (v, gid), rows in sorted(by_goal.items()):
        order = {'written': 0, 'keep': 1, 'flat': 2}
        rows.sort(key=lambda r: order.get(r[0], 9))
        ans = [(fl, _answer(g), g['label']) for fl, g in rows]
        g0 = rows[0][1]
        if len({a for _, a, _ in ans}) > 1:
            out.append('%s, goal "%s": the number of faults needed depends on how the chip was built: %s. Same source code, '
                       'different netlist, different protection.' % (v, g0['title'], ', '.join('%s (%s) in the flow "%s"' % (a, lab, FLOW_PLAIN.get(fl, fl)) for fl, a, lab in ans)))
        else:
            out.append('%s, goal "%s": %s fault(s) needed (%s) within %d cycles%s.' % (
                v, g0['title'], ans[0][1], ans[0][2], g0['spec']['cycles'],
                '' if len(ans) == 1 else ' in every flow (%s)' % ', '.join(fl for fl, _, _ in ans)))
    sizes = sorted((g['slice']['slice_share'], g['slice']['slice_cells'], g['slice']['chip_cells'], k[3], k[1], k[2]) for k, g in G.items())
    if sizes:
        lo, hi = sizes[0], sizes[-1]
        out.append('Slicing: the smallest slice is %d of %d cells (%.2f %% of the chip, goal %s); the largest is %d of %d cells '
                   '(%.1f %%, goal %s). %s' % (lo[1], lo[2], 100 * lo[0], lo[3], hi[1], hi[2], 100 * hi[0], hi[3],
                   'A goal on a dedicated check needs a tiny part of the chip; a goal on a processor register pulls in almost '
                   'everything within a few cycles.' if lo[0] < 0.05 else
                   'Every goal here sits on a processor register, so within a few cycles most of the chip can influence it: '
                   'slicing helps little and the search runs on most of the chip.'))
    C = {k: v for k, v in R['campaign'].items() if k[0] == name}
    agree = total = 0
    for k, cp in C.items():
        g = G.get(k)
        if not g or g['label'] != 'BOUNDED' or not cp['single']['complete_fault_space']:
            continue
        total += 1
        if (g['min_faults'] == 1) == (cp['single']['goal_reached'] > 0) and cp['no_fault']['goal_reached'] == 0:
            agree += 1
    if total:
        out.append('Cross-check: in %d of %d goal/netlist combinations the whole-chip simulation campaign (every cell flipped in '
                   'every cycle, sampled inputs) agrees with the exact minimum within T cycles: single-fault successes appear '
                   'exactly where that minimum is 1.' % (agree, total))
    for (c, v), inv in sorted(R['inventory'].items()):
        if c != name:
            continue
        for x in inv['rtl_scan']['items']:
            if x.get('reviewed') and x['verdict'] in ('REMOVED', 'WEAKENED') and x['reviewed'].startswith('Deliberate'):
                per = ', '.join('%s: %s' % (s['stage'], s['verdict']) for s in x['stages'])
                out.append('%s, countermeasure "%s": %s (%s). %s' % (v, x['title'], x['verdict'], per, x['reviewed']))
    return out
