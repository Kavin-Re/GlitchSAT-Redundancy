"""Generators for everything that is derived from model/variants.py:

  rtl/tops/top_<name>.v        per-experiment top wrapper (clk, one attacker input `sig`, one goal output)
  vectors/<name>.vec           cycle-by-cycle expected values from the Python model (honest, wrong inputs, faults)
  tb/gen/tb_<name>.v           self-checking Icarus Verilog testbench that replays the vector file
  build/rtl/<name>.v           one-file design (all rtl/ modules + the wrapper) for scripts/synth.sh, which reads one file
  build/manifest.json          what the cloud runner needs per variant (top, key, goal, cycles, register bits)

Generated files are deterministic; tests/test_generated.py regenerates them in memory and compares with the files
on disk. Run: python3 -m engine.wrappers            (writes all of the above)
"""
import json, os, random, sys
from model import spec as S
from model.secboot_model import Core
from model.variants import VARIANTS, Variant, wrapper_trace

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RTL_FILES = ('sb_keccak_round.v', 'sb_hash.v', 'sb_cmp.v', 'secboot_core.v')
VEC_FIELDS = ('K', 'SIG', 'F1', 'M1', 'F2', 'M2', 'F3', 'M3', 'F4', 'M4',
              'GOAL', 'ST', 'WORD', 'TOK', 'ALARM', 'BUSY', 'DONE', 'READY')
MAXFLIPS = 4


def vhex(width, value):
    return f"{width}'h{value:X}"


# ---------------------------------------------------------------- wrapper
def wrapper_verilog(v: Variant):
    c = v.cfg
    sig_to_blk = 'sig' if c.HASH_EN else vhex(c.R, 0)
    sig_to_tag = vhex(c.TAG, 0) if c.HASH_EN else 'sig'
    if v.goal == 'word':
        goal_decl = 'output wire [7:0] boot_word'
        goal_assign = 'assign boot_word = word;'
        goal_text = f'boot_word == 0x{v.goal_value:02X} (ACCEPT)'
    else:
        goal_decl = f'output wire [{v.goal_width - 1}:0] boot_grant'
        goal_assign = 'assign boot_grant = {word, token};'
        goal_text = f'boot_grant = {{boot_word, boot_token}} == 0x{v.goal_value:X} (ACCEPT and the correct token)'
    p = dict(W=c.W, RATE_LANES=c.RATE_LANES, TAG_LANES=c.TAG_LANES, NR=c.NR, KEY_BLOCKS=c.KEY_BLOCKS,
             IMG_BLOCKS=c.IMG_BLOCKS, HASH_EN=c.HASH_EN, HASH_COPIES=c.HASH_COPIES, CMP_MODE=c.CMP_MODE,
             FLAG_MUBI=c.FLAG_MUBI, SEPARATE=c.SEPARATE, ALARM_EN=c.ALARM_EN, INFECT_SPREAD=c.INFECT_SPREAD,
             CFI_EN=c.CFI_EN, OTP_REG=c.OTP_REG, TKW=c.TKW)
    plist = [f'.{k}({val})' for k, val in p.items()]
    plist += [f'.KEY({vhex(c.KEY_BLOCKS * c.R, c.KEY)})', f'.EXP_TAG({vhex(c.TAG, c.EXP_TAG)})',
              f'.TOKEN({vhex(c.TKW, c.TOKEN)})']
    lines = []
    for i in range(0, len(plist), 6):
        lines.append('    ' + ', '.join(plist[i:i + 6]) + (',' if i + 6 < len(plist) else ''))
    cms = ', '.join(v.cms)
    return f"""// GENERATED by engine/wrappers.py from model/variants.py -- do not edit by hand.
// Experiment {v.name} ({v.family}): {v.plain}
// Countermeasures: {cms}
// Attacker input: sig (8 bits, held constant); legitimate key 0x{v.key:02X}.
// {'sig is the image block hashed by the core' if c.HASH_EN else 'sig is the tag compared by the core (no hash engine)'}.
// Goal: {goal_text}.
// Tied inside: rst = 0, start = 1, blk_valid = 1; expected tag = parameter EXP_TAG (EXP_SRC = 0, exp_in unused). Solver depth: {v.cycles} cycles (honest ACCEPT at cycle {c.cycles_to_word()}).
module {v.top} (
  input  wire       clk,
  input  wire [7:0] sig,
  {goal_decl}
);
  wire [7:0]  word;
  wire [{c.TKW - 1}:0]  token;
  secboot_core #(
{chr(10).join(lines)}
  ) u_core (
    .clk(clk), .rst(1'b0), .start(1'b1), .blk_valid(1'b1), .blk_data({sig_to_blk}), .tag_in({sig_to_tag}),
    .exp_in({vhex(c.TAG, 0)}), .exp_load(1'b0), .pad_ok(1'b1),
    .state(), .boot_word(word), .boot_token(token), .alarm(), .blk_ready(), .busy(), .done(), .dbg_tag());
  {goal_assign}
endmodule
"""


def single_file_design(v: Variant):
    parts = [f'// GENERATED by engine/wrappers.py: rtl/{", rtl/".join(RTL_FILES)} and rtl/tops/{v.top}.v in one file\n'
             f'// (scripts/synth.sh reads exactly one Verilog file).\n']
    for f in RTL_FILES:
        with open(os.path.join(HERE, 'rtl', f)) as fh:
            parts.append(f'// ---- rtl/{f}\n' + fh.read())
    parts.append(f'// ---- rtl/tops/{v.top}.v\n' + wrapper_verilog(v))
    return '\n'.join(parts)


# ---------------------------------------------------------------- registers as seen from the testbench
def reg_paths(cfg):
    """(model register name, width, reset value, hierarchical path below the wrapper instance `dut`)."""
    m = Core(cfg)
    out = []
    for n in m.width:
        if n.startswith('flag'):
            path = f'dut.u_core.g_flag[{int(n[4:])}].q'
        elif n in ('step', 'step_n'):
            path = f'dut.u_core.g_cfi.{n}'
        elif n.startswith('hash'):
            path = f'dut.u_core.g_h.g_hash[{int(n[4:])}].u_hash.s'
        elif n.startswith('otp'):
            path = f'dut.u_core.g_o.g_otp[{int(n[3:])}].q'
        else:
            path = f'dut.u_core.{n}'
        out.append((n, m.width[n], m.reset_value[n], path))
    return out


# ---------------------------------------------------------------- vectors
def scenarios(v: Variant, seed=20261121):
    """List of (sig, flips) pairs. Deterministic."""
    c = v.cfg
    rng = random.Random(seed ^ sum(map(ord, v.name)))
    k = v.key
    out = [(k, {})]
    for s in sorted({k ^ 1, k ^ 0x80, 0x00, 0xFF, rng.randrange(256), rng.randrange(256)} - {k}):
        out.append((s, {}))
    regs = [(n, w) for n, w in Core(c).width.items()]
    n = v.cycles + 2
    for i in range(32):
        name, w = rng.choice(regs)
        out.append((k if i % 4 == 0 else k ^ (1 << rng.randrange(8)), {rng.randrange(n): [(name, rng.randrange(w))]}))
    t_dec = c.cycles_to_word() - 2          # cycle in which the state register holds COMPARE, phase 1
    diff = S.COMPARE ^ S.ACCEPT
    out.append((k ^ 1, {t_dec: [('st', b) for b in range(8) if diff >> b & 1]}))          # 4 flips: COMPARE -> ACCEPT
    diff = S.LOAD ^ S.COMPARE
    out.append((k, {1: [('st', b) for b in range(8) if diff >> b & 1]}))                 # 4 flips: LOAD -> COMPARE
    fl = []
    for i in range(c.NC):
        x = c.flag_true(i) ^ c.flag_false(i)
        fl += [(f'flag{i}', b) for b in range(c.FW) if x >> b & 1]
    out.append((k ^ 1, {t_dec: fl[:MAXFLIPS]}))
    return out


def vectors(v: Variant):
    ids = {n: i + 1 for i, (n, *_r) in enumerate(reg_paths(v.cfg))}
    lines = []
    n = v.cycles + 2
    for sig, flips in scenarios(v):
        lines.append(' '.join(['1'] + ['0'] * (len(VEC_FIELDS) - 1)))
        tr = wrapper_trace(v, sig, cycles=n, flips=flips)
        for t, o in enumerate(tr):
            fl = list(flips.get(t, ()))
            assert len(fl) <= MAXFLIPS
            masks = {}
            for name, bit in fl:
                masks[name] = masks.get(name, 0) | (1 << bit)
            fields = ['0', f'{sig:X}']
            for name, m in list(masks.items()) + [(None, 0)] * (MAXFLIPS - len(masks)):
                fields += [f'{ids[name]:X}' if name else '0', f'{m:X}']
            fields += [f"{o[x]:X}" for x in ('goal', 'st', 'boot_word', 'boot_token', 'alarm', 'busy', 'done', 'blk_ready')]
            lines.append(' '.join(fields))
    return '\n'.join(lines) + '\n'


# ---------------------------------------------------------------- testbench
def testbench(v: Variant):
    c = v.cfg
    regs = reg_paths(c)
    flip_cases = '\n'.join(f'        {i + 1}: {p} = {p} ^ m[{w - 1}:0];' for i, (n, w, rv, p) in enumerate(regs))
    restore = '\n'.join(f'      {p} = {vhex(w, rv)};' for n, w, rv, p in regs)
    gw = v.goal_width
    return f"""// GENERATED by engine/wrappers.py -- self-checking replay of vectors/{v.name}.vec against rtl/tops/{v.top}.v.
// Each vector line is one clock cycle: inputs and register flips are applied in the low phase, outputs are compared
// 2 ns later, then the rising edge. A flip XORs a register for that cycle only (as Core.step(flips=...) does).
// Run (from the secboot_hw directory):
//   iverilog -g2005 -o build/sim/tb_{v.name}.vvp -DVEC='"vectors/{v.name}.vec"' rtl/*.v rtl/tops/{v.top}.v tb/gen/tb_{v.name}.v
//   vvp build/sim/tb_{v.name}.vvp        (prints PASS or FAIL)
`timescale 1ns/1ps
`ifndef VEC
`define VEC "vectors/{v.name}.vec"
`endif
module tb_{v.name};
  reg clk;
  reg [7:0] sig;
  wire [{gw - 1}:0] goal;
  {v.top} dut (.clk(clk), .sig(sig), .{v.goal_port}(goal));

  integer fd, rc, errors, cycles, scen;
  reg [255:0] v0, v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12, v13, v14, v15, v16, v17;

  task flip(input [31:0] id, input [255:0] m);
    begin
      case (id)
        0: ;
{flip_cases}
        default: begin $display("FAIL bad flip id %0d", id); errors = errors + 1; end
      endcase
    end
  endtask

  task restore;
    begin
{restore}
    end
  endtask

  task chk(input [255:0] got, input [255:0] want, input [8*8-1:0] what);
    begin
      if (got !== want) begin
        errors = errors + 1;
        if (errors <= 20)
          $display("MISMATCH scenario %0d cycle %0d %0s: got %0h want %0h", scen, cycles, what, got, want);
      end
    end
  endtask

  task readline;
    begin
      rc = $fscanf(fd, "%h %h %h %h %h %h %h %h %h %h %h %h %h %h %h %h %h %h\\n",
                   v0, v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12, v13, v14, v15, v16, v17);
    end
  endtask

  initial begin   // watchdog: a hang (for example a vector-format mismatch) fails instead of blocking vvp
    #10000000;
    $display("FAIL timeout");
    $finish;
  end

  initial begin
    clk = 1'b0; sig = 8'h00; errors = 0; cycles = 0; scen = 0;
    fd = $fopen(`VEC, "r");
    if (fd == 0) begin $display("FAIL cannot open %0s", `VEC); $finish; end
    #1;
    readline;
    while (rc == 18) begin
      if (v0 == 1) begin
        restore;
        scen = scen + 1;
        cycles = 0;
      end else begin
        sig = v1[7:0];
        flip(v2, v3); flip(v4, v5); flip(v6, v7); flip(v8, v9);
        #2;
        chk(goal, v10, "goal");
        chk(dut.u_core.state, v11, "state");
        chk(dut.u_core.boot_word, v12, "word");
        chk(dut.u_core.boot_token, v13, "token");
        chk(dut.u_core.alarm, v14, "alarm");
        chk(dut.u_core.busy, v15, "busy");
        chk(dut.u_core.done, v16, "done");
        chk(dut.u_core.blk_ready, v17, "ready");
        #3 clk = 1'b1;
        #5 clk = 1'b0;
        cycles = cycles + 1;
      end
      readline;
    end
    if (!$feof(fd)) begin
      $display("FAIL malformed vector line (%0d fields read)", rc); errors = errors + 1;
    end
    $fclose(fd);
    if (errors == 0 && scen > 0)
      $display("PASS tb_{v.name}: %0d scenarios", scen);
    else
      $display("FAIL tb_{v.name}: %0d mismatches, %0d scenarios", errors, scen);
    $finish;
  end
endmodule
"""


def manifest():
    rows = []
    for v in VARIANTS:
        rows.append(dict(name=v.name, family=v.family, top=v.top, design=f'build/rtl/{v.name}.v',
                         goal_out=v.goal_port, goal_value=v.goal_value, goal_width=v.goal_width, attack_input='sig',
                         key=v.key, cycles=v.cycles, accept_cycle=v.cfg.cycles_to_word(), large=v.large,
                         countermeasures=list(v.cms), plain=v.plain, intent=v.intent,
                         model_register_bits_in_goal_cone=v.flop_bits(),
                         params={k: getattr(v.cfg, k) for k in v.cfg.__dataclass_fields__}))
    return dict(schema='secboot-hw-manifest/1',
                note='Generated by engine/wrappers.py. Register bits are exact for the RTL as written; gate counts are '
                     'not known until synthesis (cloud/cloud_run.sh).', variants=rows)


def generated_files():
    """{relative path: content} for every generated file."""
    out = {}
    for v in VARIANTS:
        out[f'rtl/tops/{v.top}.v'] = wrapper_verilog(v)
        out[f'vectors/{v.name}.vec'] = vectors(v)
        out[f'tb/gen/tb_{v.name}.v'] = testbench(v)
    return out


def write_all(root=HERE, build=True):
    files = generated_files()
    if build:
        for v in VARIANTS:
            files[f'build/rtl/{v.name}.v'] = single_file_design(v)
        files['build/manifest.json'] = json.dumps(manifest(), indent=1) + '\n'
    for rel, text in files.items():
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w') as fh:
            fh.write(text)
    return sorted(files)


if __name__ == '__main__':
    for p in write_all():
        print(p)
