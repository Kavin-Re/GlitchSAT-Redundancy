"""Fixed testbenches whose expected values come from the Python model (and, for the known-answer test, from the
published SHA3-256 values that tests/test_kat.py checks against hashlib):

  tb/gen/tb_kat.v      hash engine known-answer test: sb_hash at full size (W = 64, rate 1088) computes
                       SHA3-256("") and SHA3-256("abc"); Keccak-f[1600] of the zero state; and the small engine used
                       by the hash experiments (W = 2, 2 rounds) gives the model's tag for the key/image of h_single
  tb/gen/tb_mmio.v     register front end at the firmware's offsets: complete boots through the bus (genuine image,
     vectors/mmio.vec  tampered image, short and long messages, restart), replayed against model/mmio_model.py

Run: python3 -m engine.benches        (writes the files above)
"""
import hashlib, os, random
from model import keccak as K
from model.mmio_model import (Mmio, mmio_cfg, key_block_from_otp, run_boot, A_EXPECTED, A_CTRL, A_STATUS, A_MSG, A_VERDICT, A_TOKEN,
                              CTRL_START)
from model.variants import BY_NAME

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Published values (FIPS 202 examples / the Keccak team's KeccakF-1600 intermediate values).
SHA3_256_EMPTY = 'a7ffc6f8bf1ed76651c14756a061d662f580ff4de43b49fa82d80a4b80f8434a'
SHA3_256_ABC = '3a985da74fe225b2045c172d6bd390bd855f086e3e9d525b46bfe24511431532'
KECCAK_F1600_ZERO_LANE0 = 0xF1258F7940E1DDE7

OTP_KEY32 = bytes(range(0x40, 0x60))      # the firmware simulator's demo key (firmware/INTERFACE.md, OTP words)


def sha3_block(msg: bytes, rate_bytes=136):
    """One padded SHA-3 block for a message shorter than the rate."""
    assert len(msg) < rate_bytes
    b = bytearray(msg) + b'\x06' + bytes(rate_bytes - len(msg) - 1)
    b[-1] |= 0x80
    return int.from_bytes(bytes(b), 'little')


def digest_int(hexstr):
    return int.from_bytes(bytes.fromhex(hexstr), 'little')


def kat_tb():
    h = BY_NAME['h_single'].cfg
    small_tag = None
    from model.secboot_model import mac
    small_tag = mac(h, [BY_NAME['h_single'].key])
    abc = sha3_block(b'abc')
    nr_small = h.NR_E
    first_small = K.full_rounds(h.W) - nr_small
    return f"""// GENERATED by engine/benches.py -- known-answer test of the hash engine rtl/sb_hash.v (+ sb_keccak_round.v).
//   1. Keccak-f[1600] of the all-zero state: lane 0 = 64'h{KECCAK_F1600_ZERO_LANE0:016X} (published value)
//   2. SHA3-256("")    = {SHA3_256_EMPTY}  (engine's own pad block)
//   3. SHA3-256("abc") = {SHA3_256_ABC}  (padded block given as an image block)
//   4. small engine of the hash experiments (W={h.W}, rate {h.R} bits, {nr_small} rounds): key 0x{h.KEY:X}, image 0x{BY_NAME['h_single'].key:X}
//      -> tag 0x{small_tag:X} (from model/secboot_model.mac)
// Digest bytes are little-endian in the state (byte 0 = state bits 7:0).
// Run: iverilog -g2005 -o build/sim/tb_kat.vvp rtl/sb_keccak_round.v rtl/sb_hash.v tb/gen/tb_kat.v && vvp build/sim/tb_kat.vvp
`timescale 1ns/1ps
module tb_kat;
  reg clk;
  reg clr, absorb, round_en, is_key, is_img;
  reg [4:0] rnd;
  reg [1087:0] data;
  wire [1599:0] s64;
  reg c2, a2, r2, k2, i2;
  reg [4:0] rnd2;
  reg [{h.R - 1}:0] data2;
  wire [{h.B - 1}:0] s2;
  integer i, errors;

  sb_hash #(.W(64), .RATE_LANES(17), .KEY_BLOCKS(1), .BLKW(1), .KEY(1088'h0)) u64 (
    .clk(clk), .clr(clr), .absorb(absorb), .round_en(round_en), .is_key(is_key), .is_img(is_img), .blk(1'b0),
    .blk_data(data), .rnd(rnd), .state(s64));
  sb_hash #(.W({h.W}), .RATE_LANES({h.RATE_LANES}), .KEY_BLOCKS(1), .BLKW(1), .KEY({h.R}'h{h.KEY:X})) u2 (
    .clk(clk), .clr(c2), .absorb(a2), .round_en(r2), .is_key(k2), .is_img(i2), .blk(1'b0),
    .blk_data(data2), .rnd(rnd2), .state(s2));

  task tick; begin #5 clk = 1'b1; #5 clk = 1'b0; end endtask

  task perm64;   // 24 rounds, ir = 0..23
    begin
      absorb = 1'b0; round_en = 1'b1;
      for (i = 0; i < 24; i = i + 1) begin rnd = i; tick; end
      round_en = 1'b0;
    end
  endtask

  task block64(input img, input [1087:0] d);
    begin
      is_key = 1'b0; is_img = img; data = d; absorb = 1'b1; tick; absorb = 1'b0;
      perm64;
    end
  endtask

  task clear64; begin clr = 1'b1; tick; clr = 1'b0; end endtask

  task block2(input key, input img, input [{h.R - 1}:0] d);
    begin
      k2 = key; i2 = img; data2 = d; a2 = 1'b1; tick; a2 = 1'b0;
      r2 = 1'b1;
      for (i = {first_small}; i < {first_small + nr_small}; i = i + 1) begin rnd2 = i; tick; end
      r2 = 1'b0;
    end
  endtask

  initial begin   // watchdog: a hang (for example a vector-format mismatch) fails instead of blocking vvp
    #10000000;
    $display("FAIL timeout");
    $finish;
  end

  initial begin
    clk = 1'b0; errors = 0;
    clr = 0; absorb = 0; round_en = 0; is_key = 0; is_img = 0; rnd = 0; data = 0;
    c2 = 0; a2 = 0; r2 = 0; k2 = 0; i2 = 0; rnd2 = 0; data2 = 0;
    #1;
    // 1. permutation of the zero state
    clear64; perm64;
    if (s64[63:0] !== 64'h{KECCAK_F1600_ZERO_LANE0:016X}) begin errors = errors + 1; $display("FAIL keccak-f zero state: %h", s64[63:0]); end
    // 2. SHA3-256 of the empty message: the engine's pad block (is_key = 0, is_img = 0)
    clear64; block64(1'b0, 1088'h0);
    if (s64[255:0] !== 256'h{digest_int(SHA3_256_EMPTY):064X}) begin errors = errors + 1; $display("FAIL sha3-256(empty): %h", s64[255:0]); end
    // 3. SHA3-256("abc"): the padded block as image data
    clear64; block64(1'b1, 1088'h{abc:X});
    if (s64[255:0] !== 256'h{digest_int(SHA3_256_ABC):064X}) begin errors = errors + 1; $display("FAIL sha3-256(abc): %h", s64[255:0]); end
    // 4. small engine: key block, image block, pad block
    c2 = 1'b1; tick; c2 = 1'b0;
    block2(1'b1, 1'b0, {h.R}'h0);
    block2(1'b0, 1'b1, {h.R}'h{BY_NAME['h_single'].key:X});
    block2(1'b0, 1'b0, {h.R}'h0);
    if (s2[{h.TAG - 1}:0] !== {h.TAG}'h{small_tag:X}) begin errors = errors + 1; $display("FAIL small engine tag: %h", s2[{h.TAG - 1}:0]); end
    if (errors == 0) $display("PASS tb_kat: 4 known answers");
    else $display("FAIL tb_kat: %0d errors", errors);
    $finish;
  end
endmodule
"""


# ---------------------------------------------------------------- MMIO
def mmio_setup():
    """Default bus build (EXP_SRC = 1: expected tag written to EXPECTED, EXP_TAG parameter unused and left 0)."""
    rng = random.Random(2026)
    msg = bytes(rng.randrange(256) for _ in range(272))
    cfg = mmio_cfg(KEY=key_block_from_otp(OTP_KEY32))
    d = hashlib.sha3_256(OTP_KEY32 + bytes(104) + msg).digest()
    words = [int.from_bytes(msg[i:i + 4], 'little') for i in range(0, len(msg), 4)]
    return cfg, msg, words, d


def mmio_second_image():
    """A second, different image for the same build, and its tag."""
    rng = random.Random(2027)
    msg = bytes(rng.randrange(256) for _ in range(272))
    d = hashlib.sha3_256(OTP_KEY32 + bytes(104) + msg).digest()
    return msg, [int.from_bytes(msg[i:i + 4], 'little') for i in range(0, len(msg), 4)], d


def mmio_ops():
    """All bus cycles of the MMIO scenarios, in order, on one Mmio instance from power-up."""
    cfg, msg, words, d = mmio_setup()
    _, words2, d2 = mmio_second_image()
    e1, e2 = int.from_bytes(d, 'little'), int.from_bytes(d2, 'little')
    m = Mmio(cfg)
    ops = []
    results = {}
    tampered = list(words); tampered[7] ^= 0x100
    for name, w, e in (('genuine', words, e1), ('tampered', tampered, e1), ('short', words[:-1], e1),
                       ('long', words + [0], e1), ('genuine_again', words, e1),
                       ('second_image', words2, e2),          # another image, its own tag: same build accepts it
                       ('wrong_expected', words, e2),         # genuine image, expected tag of the other image
                       ('no_expected', words, None)):         # EXPECTED never written (cleared by START)
        r = run_boot(m, w, expected=e)
        ops += r['ops']
        results[name] = r
    for w in words[:40]:                          # restart: half a message, then a complete genuine boot
        r0 = m.step(1, A_MSG, w)
        ops.append((1, A_MSG, w, r0, m.stall))
    r = run_boot(m, words, expected=e1)
    ops += r['ops']
    results['restart'] = r
    # EXPECTED written only after FINISH: ignored, the compare uses the cleared value and rejects
    r = run_boot(m, words, expected=None)
    for i in range(8):
        r0 = m.step(1, A_EXPECTED + 4 * i, (e1 >> (32 * i)) & 0xFFFFFFFF)
        r['ops'].append((1, A_EXPECTED + 4 * i, (e1 >> (32 * i)) & 0xFFFFFFFF, r0, m.stall))
    for a in (A_VERDICT, A_TOKEN, A_EXPECTED):    # EXPECTED is write-only: reads 0
        r0 = m.step(0, a)
        r['ops'].append((0, a, 0, r0, m.stall))
        r['late_' + {A_VERDICT: 'verdict', A_TOKEN: 'token', A_EXPECTED: 'expected_read'}[a]] = r0
    ops += r['ops']
    results['late_expected'] = r
    return cfg, ops, results


def mmio_vectors():
    cfg, ops, results = mmio_ops()
    lines = [f'{we:X} {addr:X} {wdata:X} {rdata:X} {stall:X}' for we, addr, wdata, rdata, stall in ops]
    return '\n'.join(lines) + '\n', cfg, results


def mmio_tb(cfg):
    return f"""// GENERATED by engine/benches.py -- self-checking replay of vectors/mmio.vec against rtl/secboot_mmio.v.
// Each line is one bus cycle: WE ADDR WDATA expected-RDATA expected-STALL (hex). Scenarios, back to back from
// power-up: genuine boot (expect VERDICT 0x96, TOKEN 0x{cfg.TOKEN:08X}), tampered image, short message, long
// message, genuine again, a second image with its own tag (accepted by the same build), the genuine image with the
// other image's tag, no EXPECTED written, half a message followed by START and a genuine boot, and EXPECTED written
// only after FINISH (ignored). Key = OTP demo key 0x40..0x5F, zero-filled to one 136-byte block. Each boot writes
// its expected tag to EXPECTED[0..7] (0x60..0x7C) before the message (EXP_SRC = {cfg.EXP_SRC}).
// Run: iverilog -g2005 -o build/sim/tb_mmio.vvp rtl/*.v tb/gen/tb_mmio.v && vvp build/sim/tb_mmio.vvp
`timescale 1ns/1ps
`ifndef VEC
`define VEC "vectors/mmio.vec"
`endif
module tb_mmio;
  reg clk, we;
  reg [7:0] addr;
  reg [31:0] wdata;
  wire [31:0] rdata;
  wire stall, alarm;
  wire [7:0] word;
  wire [31:0] token;
  integer fd, rc, errors, n;
  reg [31:0] x_we, x_addr, x_wdata, x_rdata, x_stall;

  secboot_mmio #(
    .W({cfg.W}), .RATE_LANES({cfg.RATE_LANES}), .TAG_LANES({cfg.TAG_LANES}), .NR({cfg.NR}), .KEY_BLOCKS({cfg.KEY_BLOCKS}),
    .IMG_BLOCKS({cfg.IMG_BLOCKS}), .HASH_COPIES({cfg.HASH_COPIES}), .CMP_MODE({cfg.CMP_MODE}), .FLAG_MUBI({cfg.FLAG_MUBI}),
    .SEPARATE({cfg.SEPARATE}), .ALARM_EN({cfg.ALARM_EN}), .INFECT_SPREAD({cfg.INFECT_SPREAD}), .CFI_EN({cfg.CFI_EN}),
    .OTP_REG({cfg.OTP_REG}), .EXP_SRC({cfg.EXP_SRC}), .TKW({cfg.TKW}),
    .KEY({cfg.KEY_BLOCKS * cfg.R}'h{cfg.KEY:X}),
    .EXP_TAG({cfg.TAG}'h{cfg.EXP_TAG:X}),
    .TOKEN({cfg.TKW}'h{cfg.TOKEN:X})
  ) dut (.clk(clk), .rst(1'b0), .we(we), .addr(addr), .wdata(wdata), .rdata(rdata), .stall(stall),
         .boot_word(word), .boot_token(token), .alarm(alarm));

  initial begin   // watchdog: a hang (for example a vector-format mismatch) fails instead of blocking vvp
    #10000000;
    $display("FAIL timeout");
    $finish;
  end

  initial begin
    clk = 1'b0; we = 1'b0; addr = 8'h00; wdata = 32'h0; errors = 0; n = 0;
    fd = $fopen(`VEC, "r");
    if (fd == 0) begin $display("FAIL cannot open %0s", `VEC); $finish; end
    #1;
    rc = $fscanf(fd, "%h %h %h %h %h\\n", x_we, x_addr, x_wdata, x_rdata, x_stall);
    while (rc == 5) begin
      we = x_we[0]; addr = x_addr[7:0]; wdata = x_wdata;
      #2;
      if (rdata !== x_rdata || stall !== x_stall[0]) begin
        errors = errors + 1;
        if (errors <= 20) $display("MISMATCH bus cycle %0d addr %h: rdata %h want %h, stall %b want %b", n, addr, rdata, x_rdata, stall, x_stall[0]);
      end
      #3 clk = 1'b1;
      #5 clk = 1'b0;
      n = n + 1;
      rc = $fscanf(fd, "%h %h %h %h %h\\n", x_we, x_addr, x_wdata, x_rdata, x_stall);
    end
    if (!$feof(fd)) begin errors = errors + 1; $display("FAIL malformed vector line"); end
    if (errors == 0 && n > 0) $display("PASS tb_mmio: %0d bus cycles", n);
    else $display("FAIL tb_mmio: %0d mismatches in %0d bus cycles", errors, n);
    $finish;
  end
endmodule
"""


def generated_files():
    vec, cfg, _ = mmio_vectors()
    return {'tb/gen/tb_kat.v': kat_tb(), 'tb/gen/tb_mmio.v': mmio_tb(cfg), 'vectors/mmio.vec': vec}


def write_all(root=HERE):
    files = generated_files()
    for rel, text in files.items():
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w') as fh:
            fh.write(text)
    return sorted(files)


if __name__ == '__main__':
    for p in write_all():
        print(p)
