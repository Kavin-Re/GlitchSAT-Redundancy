#!/usr/bin/env python3
"""Benchmark the SAT backend: CNF size for every design, solve time per fault budget, optional comparison with the z3
engine (scripts/glitchsat.py check) where z3 is installed and finishes inside --z3-timeout.

  bench.py --set core|proxy|repo|all [--backend B] [--k 1 2 3] [--timeout S] [--z3] [--z3-timeout S]
           [--r20-dir DIR] [--no-collapse] [--out FILE.json] [--md FILE.md]

Design sets
  core   V0/V1/V2 (reference spike + stored RTL plain-flow netlists), V5, V2 spike at 12 and 20 cycles, the OTP FSM
  proxy  S-box proxy netlists generated by gen_sbox_proxy.py (NOT the R20 netlists)
  repo   every distinct netlist in the repository with sig/boot_word ports (6 cycles; key/goal from
         research/c4/ver/manifest.json where given, else 0xC3/0x96 cut to the port widths)
  r20    the R20 designs synthesised by cloud_bench.sh with yosys into --r20-dir (only if that directory has them)
Every number printed is measured by this run on this machine. Timings are wall-clock, single run, no repetition.
"""
import argparse, json, os, subprocess, sys, tempfile, time
from common import S, ROOT, FASTSAT, repo_netlists, default_params
import gen_sbox_proxy


def core_designs():
    ds = []
    for d in ('v0', 'v1', 'v2'):
        ds.append(dict(name=f'{d} spike', path=f'reference/spike_netlists/{d}.json', top=d, T=6))
    for d in ('v0', 'v1', 'v2'):
        ds.append(dict(name=f'{d} rtl plain', path=f'results/deep/work/nl/{d}_rtl.json', top=d, T=6))
    ds.append(dict(name='v5 (apt 0.33)', path='research/c4/b3/nl/v5_apt033.json', top='v5', T=6))
    ds.append(dict(name='v2 spike T=12', path='reference/spike_netlists/v2.json', top='v2', T=12))
    ds.append(dict(name='v2 spike T=20', path='reference/spike_netlists/v2.json', top='v2', T=20))
    # engine semantics on the OTP FSM netlist (NOT the threat model of real_designs/REPORT.md, which uses an adapted
    # solver with per-cycle inputs): goal unlock == 1, attacker port user_digit != 0, other inputs free constants
    ds.append(dict(name='otp fsm5 (engine semantics)', path='real_designs/fsm5.json', top='wrapper', T=6,
                   goal_out='unlock', goal_value=1, attack_in='user_digit', key=0))
    return [d for d in ds if os.path.isfile(os.path.join(ROOT, d['path']))]


def proxy_designs(workdir, T=None):
    os.makedirs(workdir, exist_ok=True)
    box = gen_sbox_proxy.aes_sbox(); ds = []
    for shared in (False, True):
        for kind, p in gen_sbox_proxy.PARAMS.items():
            b = gen_sbox_proxy.build(kind, box, shared)
            path = os.path.join(workdir, b.top + '.json')
            with open(path, 'w') as f: json.dump(b.doc(), f)
            ds.append(dict(name=b.top.replace('sbox_', '').replace('_proxy', ' (proxy)'), path=path, top=b.top, T=T or p['cycles'],
                           goal_out=p['goal_out'], goal_value=p['goal_value'], key=p['key']))
    return ds


R20 = {  # file stem -> (top, goal_out, goal_value, key, cycles)   parameters from research/c3/r20/out/*.json
    'sbox_unprot': ('sbox_unprot', 'y', 0x7C, 1, 4), 'sbox_par': ('sbox_par', 'gout', 0x17C, 1, 4),
    'sbox_par2': ('sbox_par2', 'gout', 0x17C, 1, 4), 'sbox_dmr': ('sbox_dmr', 'gout', 0x17C, 1, 4),
    'crc_plain': ('bootcrc', 'ok', 1, 0xA5, 4), 'crc_tmr': ('bootcrc_tmr', 'ok', 1, 0xA5, 4), 'uart': ('uartw', 'gout', 7, 0, 6)}


def r20_designs(d):
    ds = []
    for stem, (top, go, gv, key, T) in R20.items():
        p = os.path.join(d, stem + '.json')
        if os.path.isfile(p):
            ds.append(dict(name=f'R20 {stem}', path=p, top=top, T=T, goal_out=go, goal_value=gv, key=key))
    return ds


def repo_designs():
    ds = []
    for n in repo_netlists():
        if n['ports'].get('sig', (None,))[0] == 'input' and n['ports'].get('boot_word', (None,))[0] == 'output':
            kw, _ = default_params(n)
            ds.append(dict(name=n['path'], path=n['path'], top=n['top'], T=6, **kw))
    return ds


def kw_of(d):
    return dict(goal_out=d.get('goal_out', 'boot_word'), goal_value=d.get('goal_value', 0x96),
                attack_in=d.get('attack_in', 'sig'), key=d.get('key', 0xC3))


def z3_available():
    return subprocess.run([sys.executable, '-c', 'import z3'], capture_output=True).returncode == 0


def run_z3(d, k, timeout_s):
    """scripts/glitchsat.py check in a subprocess, killed at timeout_s. Returns dict(verdict, min, s)."""
    kw = kw_of(d)
    with tempfile.TemporaryDirectory() as td:
        out = os.path.join(td, 'r.json')
        cmd = [sys.executable, os.path.join(ROOT, 'scripts', 'glitchsat.py'), 'check', os.path.join(ROOT, d['path']), '--top', d['top'],
               '--k', str(k), '--cycles', str(d['T']), '--goal-out', kw['goal_out'], '--goal-value', hex(kw['goal_value']),
               '--attack-input', kw['attack_in'], '--key', hex(kw['key']), '--out', out, '--timeout-ms', str(int(timeout_s * 1000))]
        t0 = time.time()
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_s + 30)
        except subprocess.TimeoutExpired:
            return dict(verdict='TIMEOUT(outer)', min=None, s=round(time.time() - t0, 1))
        wall = round(time.time() - t0, 2)
        if not os.path.isfile(out):
            return dict(verdict=f'ERROR(exit {r.returncode})', min=None, s=wall, err=r.stderr[-200:])
        j = json.load(open(out))
        return dict(verdict=j['verdict'], min=j.get('min_faults'), s=j['runtime_s']['solve_and_minimize'], wall=wall)


def bench_design(d, a):
    path = os.path.join(ROOT, d['path'])
    row = dict(name=d['name'], T=d['T'])
    try:
        nl = S.gs.Netlist(path, d['top'])
        kw = kw_of(d)
        row.update(nl.stats())
        kmax = max(a.k)
        e = S.encode(nl, d['T'], collapse=not a.no_collapse, fault_enc=a.fault_enc, **kw)
        circ = e.stats()
        S.add_cardinality(e, min(kmax, len(e.fault_order)), a.card)
        row.update(sites_modelled=e.info['sites_modelled'], fault_vars=e.info['fault_vars'], cnf_circuit=circ, cnf=e.stats())
    except S.NetlistError as ex:
        row.update(error=str(ex)[:100]); return row
    if a.cnf_only:
        return row
    # one instance, ascending budgets (assumptions)
    t0 = time.time()
    rows, info, found = S.sweep(nl, d['T'], kmax, timeout_ms=int(a.timeout * 1000),
                                backend=a.backend, card=a.card, collapse=not a.no_collapse, fault_enc=a.fault_enc, **kw)
    row.update(backend=info['backend'], sweep=rows, sweep_wall_s=round(time.time() - t0, 3), build_s=info['build_s'])
    m = next((r['min_faults'] for r in rows if 'min_faults' in r), None)
    row['min'] = m if rows[-1]['verdict'] != 'UNKNOWN_TIMEOUT' else 'unknown'
    row['per_k'] = {}
    for k in a.k:
        cell = {}
        if a.per_k:                               # fresh instance per budget: what `check --k K` costs (build + solve + minimise)
            t0 = time.time()
            v, info, res = S.solve(nl, d['T'], k, timeout_ms=int(a.timeout * 1000), backend=a.backend, card=a.card,
                                   collapse=not a.no_collapse, fault_enc=a.fault_enc, **kw)
            cell.update(verdict=v, min=len(res['faults']) if res else None, s=round(time.time() - t0, 3))
        else:
            r = rows[k] if k < len(rows) else None
            cell.update(verdict=r['verdict'] if r else 'UNKNOWN_TIMEOUT', min=r.get('min_faults') if r else None)
        if a.z3:
            z = run_z3(d, k, a.z3_timeout)
            cell['z3'] = z
            if z['verdict'] in ('ATTACK_FOUND', 'NO_ATTACK_UP_TO_BOUND') and cell['verdict'] in ('ATTACK_FOUND', 'NO_ATTACK_UP_TO_BOUND'):
                cell['agree'] = z['verdict'] == cell['verdict'] and z['min'] == cell['min']
            else:
                cell['agree'] = None                # one side has no verdict: nothing to compare
        row['per_k'][k] = cell
    return row


def fmt_table(rows, a):
    L = []
    hdr = ['design', 'gates/flops', 'T', 'sites', 'fault vars', 'CNF vars', 'CNF clauses']
    if not a.cnf_only:
        hdr += ['min<=%d' % max(a.k), 'sweep s'] + [f'k<={j} s' for j in range(max(a.k) + 1)]
        if a.per_k: hdr += [f'check k={k} s' for k in a.k]
        if a.z3: hdr += [f'z3 k={k}' for k in a.k] + ['agree']
    L.append('| ' + ' | '.join(hdr) + ' |'); L.append('|' + '---|' * len(hdr))
    for r in rows:
        if 'error' in r:
            L.append(f"| {r['name']} | - | {r['T']} | rejected: {r['error']} |" + ' |' * (len(hdr) - 4)); continue
        c = [r['name'], f"{r['gates']}/{r['flops']}", r['T'], r['sites_modelled'], r['fault_vars'], r['cnf']['vars'], r['cnf']['clauses']]
        if not a.cnf_only:
            c += [('none' if r['min'] is None else r['min']), r['sweep_wall_s']]
            for j in range(max(a.k) + 1):
                s = r['sweep'][j] if j < len(r['sweep']) else None
                c.append('-' if s is None else ('timeout' if s['verdict'] == 'UNKNOWN_TIMEOUT' else ('(implied)' if 'implied_by' in s else s['solve_s'])))
            if a.per_k: c += [('timeout' if r['per_k'][k]['verdict'] == 'UNKNOWN_TIMEOUT' else r['per_k'][k]['s']) for k in a.k]
            if a.z3:
                ag = []
                for k in a.k:
                    z = r['per_k'][k]['z3']
                    c.append(f"{'none' if z['verdict'] == 'NO_ATTACK_UP_TO_BOUND' else ('min %s' % z['min'] if z['verdict'] == 'ATTACK_FOUND' else z['verdict'])} {z['s']}s")
                    ag.append({True: 'yes', False: 'NO', None: 'n/a'}[r['per_k'][k]['agree']])
                c.append('/'.join(ag))
        L.append('| ' + ' | '.join(str(x) for x in c) + ' |')
    return '\n'.join(L)


def fmt_z3_table(rows, a):
    """One line per design and budget: SAT verdict/minimum and time next to the z3 engine's, and whether they agree.
    SAT time is the fresh `check --k K` time when --per-k was given (build + solve + minimise, the figure comparable
    with z3's solve_and_minimize), else the solve time of that budget inside the one-instance sweep."""
    def v(verdict, m):
        return {'ATTACK_FOUND': f'ATTACK min {m}', 'NO_ATTACK_UP_TO_BOUND': 'none'}.get(verdict, verdict)
    L = ['| design | gates/flops | T | k | SAT verdict | SAT s | z3 verdict | z3 s | agree | z3 s / SAT s |', '|' + '---|' * 10]
    for r in rows:
        if 'per_k' not in r:
            continue
        for k in a.k:
            c = r['per_k'][k]; z = c.get('z3', {})
            if a.per_k:
                ss = c.get('s')
            else:
                sw = r['sweep'][k] if k < len(r['sweep']) else None
                ss = sw['solve_s'] if sw else None
            ag = {True: 'yes', False: 'DIFFERENT', None: 'n/a (no verdict on one side)'}[c.get('agree')]
            both = c.get('agree') is not None and ss and z.get('s')
            ratio = f"{z['s'] / ss:.1f}" if both and ss > 0 else '-'
            L.append(f"| {r['name']} | {r['gates']}/{r['flops']} | {r['T']} | {k} | {v(c['verdict'], c.get('min'))} | "
                     f"{'timeout' if c['verdict'] == 'UNKNOWN_TIMEOUT' else ss} | {v(z.get('verdict'), z.get('min'))} | {z.get('s')} | {ag} | {ratio} |")
    return '\n'.join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--set', nargs='+', default=['core'], choices=['core', 'proxy', 'repo', 'r20', 'all'])
    ap.add_argument('--backend', default='auto'); ap.add_argument('--k', type=int, nargs='+', default=[1, 2, 3])
    ap.add_argument('--timeout', type=float, default=300, help='seconds per solver call / per check')
    ap.add_argument('--card', default='totalizer'); ap.add_argument('--fault-enc', default='xor'); ap.add_argument('--no-collapse', action='store_true')
    ap.add_argument('--cnf-only', action='store_true'); ap.add_argument('--per-k', action='store_true', help='also time a fresh `check` per budget')
    ap.add_argument('--z3', action='store_true', help='also run scripts/glitchsat.py check (needs z3-solver) and compare'); ap.add_argument('--z3-timeout', type=float, default=300)
    ap.add_argument('--r20-dir', default=os.path.join(FASTSAT, 'bench', 'work', 'r20')); ap.add_argument('--proxy-cycles', type=int)
    ap.add_argument('--only', help='substring filter on design names')
    ap.add_argument('--out'); ap.add_argument('--md')
    a = ap.parse_args()
    if a.z3 and not z3_available():
        print('z3-solver is not installed: comparison with the z3 engine is skipped', file=sys.stderr); a.z3 = False
    sets = set(a.set)
    if 'all' in sets: sets = {'core', 'proxy', 'repo', 'r20'}
    ds = []
    if 'core' in sets: ds += core_designs()
    if 'r20' in sets: ds += r20_designs(a.r20_dir)
    if 'proxy' in sets: ds += proxy_designs(os.path.join(FASTSAT, 'bench', 'work', 'proxy'), a.proxy_cycles)
    if 'repo' in sets: ds += repo_designs()
    if a.only: ds = [d for d in ds if a.only in d['name']]
    rows = []
    for d in ds:
        r = bench_design(d, a); rows.append(r)
        print(f"  done {r['name']}" + (f"  min={r.get('min')}  sweep={r.get('sweep_wall_s')}s" if 'sweep' in r else ''), file=sys.stderr, flush=True)
    be = rows and next((r.get('backend') for r in rows if r.get('backend')), None)
    head = (f"backend sat:{be}  card={a.card}  fault-enc={a.fault_enc}  collapse={'off' if a.no_collapse else 'on'}  "
            f"python {sys.version.split()[0]}  cpus {os.cpu_count()}  timeout {a.timeout}s" + (f"  z3-timeout {a.z3_timeout}s" if a.z3 else ''))
    tab = fmt_table(rows, a)
    print(head); print(tab)
    if a.z3:
        print('\nAgreement and timing against the z3 engine (scripts/glitchsat.py check); every number measured by this run. '
              'The ratio column is single-run wall time on this machine, not a general speed-up figure.')
        print(fmt_z3_table(rows, a))
        tab += '\n\n' + fmt_z3_table(rows, a)
        cells = [c for r in rows if 'per_k' in r for c in r['per_k'].values()]
        print(f"agreement with z3: {sum(c['agree'] is True for c in cells)} equal, {sum(c['agree'] is False for c in cells)} DIFFERENT, "
              f"{sum(c['agree'] is None for c in cells)} not comparable (a side had no verdict)")
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        rec_args = dict(vars(a))   # record repository-relative paths only (no absolute path of the machine that ran it)
        if rec_args.get('r20_dir'):
            rec_args['r20_dir'] = os.path.relpath(os.path.abspath(rec_args['r20_dir']), ROOT)
        json.dump(dict(label='MEASURED', when=time.strftime('%Y-%m-%d %H:%M:%S'), config=head, args=rec_args, rows=rows), open(a.out, 'w'), indent=1)
    if a.md:
        with open(a.md, 'w') as f: f.write(head + '\n\n' + tab + '\n')
    bad = [r for r in rows if any(c.get('agree') is False for c in r.get('per_k', {}).values())]
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
