"""Nangate45 -> GlitchSAT cell adapter.

Maps every cell of a Yosys JSON gate-level netlist synthesised with the Nangate45 Open Cell Library onto the
primitives that the GlitchSAT engine (scripts/glitchsat.py, class Netlist) accepts: $_AND_, $_OR_, $_XOR_, $_NOT_,
$_MUX_ and $_DFF_P_.

Source of truth for each cell's Boolean function: SYNFI's cell library module (lowRISC/synfi,
cell_lib_nangate45_autogen.py, generated by SYNFI from NangateOpenCellLibrary_typical.lib). Two things are read
from it per (cell, output pin):
  * the documented function in the docstring ("ZN = !((A1 & A2) | (B1 & B2))"), parsed into a primitive tree;
  * the CNF clauses the function adds to a solver, i.e. what SYNFI actually computes.
Every mapped (cell, pin) is checked exhaustively over all input combinations: primitive tree == docstring
expression == the unique output value allowed by SYNFI's clauses (verify_cells()). A cell whose check fails is not
mapped (the conversion raises).

Flip-flops (SYNFI models every register as Q = D, QN = !D; reset is not modelled there). Here:
  * DFF_X1/X2 -> $_DFF_P_ (init 0 unless the netlist gives one), QN -> $_NOT_(Q).
  * DFFR (active-low RN clears), DFFS (active-low SN sets), DFFRS: two reset modes
      reset_mode='deasserted' (default): the reset pins are recorded in `meta['resets']` and must be held at their
        inactive level by the analysis (query.py ties them); init = reset value, i.e. "the run starts right after
        reset was released". Exact for a run in which reset stays inactive.
      reset_mode='sync': D_eff = RN ? D : 0 (DFFS: !SN | D); the reset is sampled at the clock edge. This is an
        approximation of the asynchronous Nangate behaviour (identical at clock edges when the reset is held across
        the edge; it ignores a reset pulse between edges).
  * SDFF* (scan flops): D_eff = SE ? SI : D, then as above.
  * The clock pin is not modelled (single clock, every flop clocked each cycle); clock nets are recorded.
Latches, clock gates, tristate enables, memories: not supported (raise UnsupportedCell). TBUF/TINV are mapped as
SYNFI maps them (enable ignored: Z = A / ZN = !I) only if allow_tristate=True.

Fault sites. The GlitchSAT bit-flip model flips the value of a net. After mapping, a multi-primitive cell has
internal nets that do not exist in the real netlist; `meta['sites']` lists the nets that do exist (the original
cell output nets and flop Q nets), with the cell that drives each. query.py restricts faults to these, so a fault
always means "this Nangate cell's output is wrong", never an invented internal node.
"""
import importlib.util
import itertools
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REAL = os.path.dirname(HERE)
DEFAULT_CELL_LIB = os.path.join(REAL, 'synfi', 'cell_lib_nangate45_autogen.py')

FLOP_PINS = {  # type -> (data pin, clear pin (active low) or None, set pin (active low) or None, scan (SI, SE) or None)
    'DFF_X1': ('D', None, None, None), 'DFF_X2': ('D', None, None, None),
    'DFFR_X1': ('D', 'RN', None, None), 'DFFR_X2': ('D', 'RN', None, None),
    'DFFS_X1': ('D', None, 'SN', None), 'DFFS_X2': ('D', None, 'SN', None),
    'DFFRS_X1': ('D', 'RN', 'SN', None), 'DFFRS_X2': ('D', 'RN', 'SN', None),
    'SDFF_X1': ('D', None, None, ('SI', 'SE')), 'SDFF_X2': ('D', None, None, ('SI', 'SE')),
    'SDFFR_X1': ('D', 'RN', None, ('SI', 'SE')), 'SDFFR_X2': ('D', 'RN', None, ('SI', 'SE')),
    'SDFFS_X1': ('D', None, 'SN', ('SI', 'SE')), 'SDFFS_X2': ('D', None, 'SN', ('SI', 'SE')),
    'SDFFRS_X1': ('D', 'RN', 'SN', ('SI', 'SE')), 'SDFFRS_X2': ('D', 'RN', 'SN', ('SI', 'SE')),
}
CLOCK_PIN = 'CK'
NO_LOGIC = {'FILLCELL_X1', 'FILLCELL_X2', 'FILLCELL_X4', 'FILLCELL_X8', 'FILLCELL_X16', 'FILLCELL_X32',
            'TAPCELL_X1', 'ANTENNA_X1'}
CONST_CELLS = {'LOGIC0_X1': ('Z', '0'), 'LOGIC1_X1': ('Z', '1')}
TRISTATE = {'TBUF_X1', 'TBUF_X2', 'TBUF_X4', 'TBUF_X8', 'TBUF_X16', 'TINV_X1'}


class AdapterError(Exception):
    pass


class UnsupportedCell(AdapterError):
    pass


# ------------------------------------------------------------------ SYNFI cell library
def load_cell_lib(path=DEFAULT_CELL_LIB):
    """Import SYNFI's generated cell library module (it only imports logging and networkx)."""
    spec = importlib.util.spec_from_file_location('synfi_cell_lib', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_TOK = re.compile(r'\s*(?:(?P<id>[A-Za-z_][A-Za-z_0-9]*)|(?P<op>[!&|^()]))')


def parse_expr(s):
    """Parse a SYNFI docstring expression (operators ! & | ^, parentheses, identifiers) into a tuple tree:
    ('var', name) | ('not', x) | ('and'|'or'|'xor', x, y) | ('const', 0/1)."""
    toks, pos = [], 0
    s = s.strip().rstrip('.')
    while pos < len(s):
        m = _TOK.match(s, pos)
        if not m or m.end() == pos:
            if s[pos:].strip() == '':
                break
            raise AdapterError(f'cannot parse {s!r} at {pos}')
        toks.append(m.group('id') or m.group('op'))
        pos = m.end()
    i = 0

    def peek():
        return toks[i] if i < len(toks) else None

    def take(t=None):
        nonlocal i
        x = toks[i]
        if t is not None and x != t:
            raise AdapterError(f'expected {t} in {s!r}')
        i += 1
        return x

    # precedence: ! > & > ^ > |   (the docstrings are fully parenthesised; precedence only matters as a safeguard)
    def p_or():
        x = p_xor()
        while peek() == '|':
            take(); x = ('or', x, p_xor())
        return x

    def p_xor():
        x = p_and()
        while peek() == '^':
            take(); x = ('xor', x, p_and())
        return x

    def p_and():
        x = p_un()
        while peek() == '&':
            take(); x = ('and', x, p_un())
        return x

    def p_un():
        t = peek()
        if t == '!':
            take(); return ('not', p_un())
        if t == '(':
            take(); x = p_or(); take(')'); return x
        if t is None:
            raise AdapterError(f'unexpected end in {s!r}')
        take()
        return ('var', t)
    tree = p_or()
    if i != len(toks):
        raise AdapterError(f'trailing tokens in {s!r}')
    return tree


def eval_tree(t, env):
    k = t[0]
    if k == 'var': return env[t[1]]
    if k == 'const': return t[1]
    if k == 'not': return 1 - eval_tree(t[1], env)
    a, b = eval_tree(t[1], env), eval_tree(t[2], env)
    return a & b if k == 'and' else a | b if k == 'or' else a ^ b


def tree_vars(t, acc=None):
    acc = [] if acc is None else acc
    if t[0] == 'var':
        if t[1] not in acc: acc.append(t[1])
    elif t[0] != 'const':
        for c in t[1:]: tree_vars(c, acc)
    return acc


def simplify(t):
    """Remove double negations (SYNFI's X4 variants are written !(!(!(...)))). Function is unchanged."""
    if t[0] == 'not':
        c = simplify(t[1])
        return c[1] if c[0] == 'not' else ('not', c)
    if t[0] in ('and', 'or', 'xor'):
        return (t[0], simplify(t[1]), simplify(t[2]))
    return t


def _mux_match(t):
    """((S & B) | (A & !S)) -> ('mux', S, B, A)  meaning S ? B : A."""
    if t[0] != 'or': return None
    l, r = t[1], t[2]
    for x, y in ((l, r), (r, l)):
        if x[0] == 'and' and y[0] == 'and':
            for s, b in ((x[1], x[2]), (x[2], x[1])):
                for a, ns in ((y[1], y[2]), (y[2], y[1])):
                    if ns == ('not', s) and s[0] == 'var':
                        return ('mux', s, b, a)
    return None


def to_prims(t):
    """Tree of primitives: ('AND'|'OR'|'XOR', x, y) | ('NOT', x) | ('MUX', s, b, a) | ('var', n) | ('BUF', x)."""
    t = simplify(t)
    m = _mux_match(t)
    if m:
        return ('MUX', to_prims(m[1]), to_prims(m[2]), to_prims(m[3]))
    k = t[0]
    if k == 'var': return t
    if k == 'const': return t
    if k == 'not': return ('NOT', to_prims(t[1]))
    return (k.upper(), to_prims(t[1]), to_prims(t[2]))


def eval_prims(p, env):
    k = p[0]
    if k == 'var': return env[p[1]]
    if k == 'const': return p[1]
    if k == 'NOT': return 1 - eval_prims(p[1], env)
    if k == 'BUF': return eval_prims(p[1], env)
    if k == 'MUX': return eval_prims(p[2], env) if eval_prims(p[1], env) else eval_prims(p[3], env)
    a, b = eval_prims(p[1], env), eval_prims(p[2], env)
    return a & b if k == 'AND' else a | b if k == 'OR' else a ^ b


class _Pin:
    def __init__(self, node, name):
        self.node, self.name = node, name


class _Rec:
    def __init__(self):
        self.clauses = []

    def add_clause(self, c):
        self.clauses.append(list(c))


def clause_function(lib, fname, pins):
    """Run SYNFI's clause generator for `fname` with one variable per pin (netlist pin names; SYNFI renames S->K,
    I->L itself) and the output as the last variable. Returns (clauses, var_of_pin, out_var)."""
    var = {p: i + 3 for i, p in enumerate(pins)}         # 1 and 2 are SYNFI's constants one/zero
    out = len(pins) + 3
    inputs = {p: _Pin(p, v) for p, v in var.items()}
    inputs['node_name'] = _Pin('y', out)
    rec = _Rec()
    lib.cell_mapping[fname](inputs, None, rec)
    return rec.clauses, var, out


def clause_truth(clauses, var, out, env):
    """Set of output values (subset of {0,1}) consistent with the clauses for input assignment env."""
    ok = []
    for y in (0, 1):
        val = {1: 1, 2: 0, out: y}
        val.update({var[p]: env[p] for p in var})
        if all(any((val[abs(l)] == 1) == (l > 0) for l in c) for c in clauses):
            ok.append(y)
    return ok


_RET = re.compile(r'Returns:\s*\n\s*(\w+)\s*=\s*(.+)')


def cell_functions(lib):
    """{cell_type: {out_pin: (expr_string, tree, input_pins)}} for every combinational cell function in the library.
    Input pins are taken from the docstring's Args line (SYNFI names) and translated back to netlist pin names."""
    out = {}
    for cell in lib.gate_in_type:
        if not re.fullmatch(r'[A-Z0-9]+_X[0-9]+', cell) or cell in lib.registers:
            continue                                     # SYNFI-internal node types and registers (Q = D there)
        for key, fn in lib.cell_mapping.items():
            if not key.startswith(cell + '_') or fn.__name__ != key:
                continue
            pin = key[len(cell) + 1:]
            doc = fn.__doc__ or ''
            m = _RET.search(doc)
            if not m or m.group(1) != pin:
                raise AdapterError(f'{key}: no "Returns: {pin} = ..." in docstring')
            tree = parse_expr(m.group(2))
            out.setdefault(cell, {})[pin] = (m.group(2).strip(), tree)
    return out


def cell_input_pins(lib, cell, pin):
    """All input pins of (cell, out pin) as the netlist names them. SYNFI's pin lists use renamed pins (S->K, I->L,
    so CI->CL); Nangate45 has no combinational pin containing K or L, so the reverse rename is unambiguous."""
    pins = lib.in_type_pins[lib.gate_in_type_out[f'{cell}_{pin}']] - {'node_name'}
    return sorted(p.replace('K', 'S').replace('L', 'I') for p in pins)


def verify_cells(lib=None, cells=None):
    """Exhaustive check of every (cell, output pin): primitive tree == docstring expression == SYNFI clauses.
    Returns a report dict; raises AdapterError on the first mismatch."""
    lib = lib or load_cell_lib()
    funcs = cell_functions(lib)
    rep = {}
    for cell in sorted(cells or funcs):
        if cell not in funcs:
            raise UnsupportedCell(cell)
        for pin, (expr, tree) in sorted(funcs[cell].items()):
            prims = to_prims(tree)
            ins = cell_input_pins(lib, cell, pin)
            missing = set(tree_vars(tree)) - set(ins)
            if missing:
                raise AdapterError(f'{cell}.{pin}: expression uses pins {missing} that the cell does not have')
            # pins as the SYNFI function expects them (netlist names; rename to K/L happens inside SYNFI)
            clauses, var, outv = clause_function(lib, f'{cell}_{pin}', ins)
            n = 0
            for bits in itertools.product((0, 1), repeat=len(ins)):
                env = dict(zip(ins, bits))
                e = eval_tree(tree, env)
                p = eval_prims(prims, env)
                c = clause_truth(clauses, var, outv, env)
                if not (e == p and c == [e]):
                    raise AdapterError(f'{cell}.{pin} mismatch at {env}: expr={e} prims={p} synfi_clauses={c}')
                n += 1
            rep[f'{cell}.{pin}'] = dict(expr=expr, inputs=ins, rows_checked=n, prims=prim_str(prims),
                                        n_prims=count_prims(prims))
    return rep


def prim_str(p):
    k = p[0]
    if k == 'var': return p[1]
    if k == 'const': return str(p[1])
    return f"{k}(" + ', '.join(prim_str(x) for x in p[1:]) + ')'


def count_prims(p):
    if p[0] in ('var', 'const'): return 0
    return 1 + sum(count_prims(x) for x in p[1:])


# ------------------------------------------------------------------ netlist conversion
class _Builder:
    def __init__(self, next_net):
        self.cells = {}
        self.next = next_net
        self.internal = {}

    def net(self, hint):
        b = self.next; self.next += 1
        self.internal[b] = hint
        return b

    def add(self, name, typ, con):
        if name in self.cells:
            raise AdapterError(f'duplicate primitive name {name}')
        dirs = {p: ('output' if p in ('Y', 'Q') else 'input') for p in con}
        self.cells[name] = dict(hide_name=0, type=typ, parameters={}, attributes={}, port_directions=dirs,
                                connections={p: [v] for p, v in con.items()})


def _emit(bld, cname, p, pinnet, out_net, ctr):
    """Emit primitive tree p; the root drives out_net (if given). Returns the net of p."""
    k = p[0]
    if k == 'var':
        src = pinnet[p[1]]
        if out_net is None:
            return src
        # a cell whose function is a plain wire (BUF): two inverters keep the engine's primitive set
        mid = bld.net(f'{cname}/buf')
        bld.add(f'{cname}/p{ctr[0]}', '$_NOT_', dict(A=src, Y=mid)); ctr[0] += 1
        bld.add(f'{cname}/p{ctr[0]}', '$_NOT_', dict(A=mid, Y=out_net)); ctr[0] += 1
        return out_net
    if k == 'const':
        raise AdapterError(f'{cname}: constant function not supported')
    args = [_emit(bld, cname, x, pinnet, None, ctr) for x in p[1:]]
    y = out_net if out_net is not None else bld.net(f'{cname}/n{ctr[0]}')
    name = f'{cname}/p{ctr[0]}'; ctr[0] += 1
    if k == 'NOT': bld.add(name, '$_NOT_', dict(A=args[0], Y=y))
    elif k == 'MUX': bld.add(name, '$_MUX_', dict(S=args[0], B=args[1], A=args[2], Y=y))
    else: bld.add(name, '$_' + k + '_', dict(A=args[0], B=args[1], Y=y))
    return y


def convert(doc, top, lib=None, reset_mode='deasserted', allow_tristate=False, flop_init=None):
    """Convert a Yosys JSON netlist of Nangate45 cells into a GlitchSAT primitive netlist.

    Returns (new_doc, meta). new_doc is a Yosys-JSON document with one module `top` containing only primitives.
    meta: {'sites': {net: {'cell', 'type', 'pin', 'kind'}}, 'cells': {cell: {'type', 'outputs': {pin: net},
    'inputs': {pin: net}, 'prims': [names]}}, 'resets': [{'net', 'active', 'cells'}], 'clocks': [...],
    'flops': {cell: {...}}, 'reset_mode'}."""
    if reset_mode not in ('deasserted', 'sync'):
        raise ValueError('reset_mode must be deasserted or sync')
    lib = lib or load_cell_lib()
    funcs = cell_functions(lib)
    m = doc['modules'][top]
    maxnet = 1
    for x in m['netnames'].values():
        for b in x['bits']:
            if isinstance(b, int): maxnet = max(maxnet, b)
    for p in m['ports'].values():
        for b in p['bits']:
            if isinstance(b, int): maxnet = max(maxnet, b)
    bld = _Builder(maxnet + 1)
    flop_init = flop_init or {}
    meta = dict(sites={}, cells={}, resets={}, clocks=set(), flops={}, reset_mode=reset_mode,
                unsupported=[], tristate=[])
    verified = set()

    def bit(c, pin, cn):
        v = c['connections'].get(pin)
        if v is None or len(v) != 1:
            raise AdapterError(f'cell {cn}: pin {pin} missing or not 1 bit')
        v = v[0]
        if v == 'x' or v == 'z':
            raise AdapterError(f'cell {cn}: pin {pin} is {v!r}')
        return v

    for cn, c in m['cells'].items():
        t = c['type']
        dirs = c.get('port_directions', {})
        if t in NO_LOGIC:
            continue
        info = dict(type=t, outputs={}, inputs={}, prims=[])
        before = set(bld.cells)
        if t in CONST_CELLS:
            raise UnsupportedCell(f'{cn}: {t} (tie cell) not supported; tie the net in the netlist instead')
        if t in FLOP_PINS:
            dp, rp, sp, scan = FLOP_PINS[t]
            d = bit(c, dp, cn)
            info['inputs'][dp] = d
            if scan:
                si, se = bit(c, scan[0], cn), bit(c, scan[1], cn)
                info['inputs'].update({scan[0]: si, scan[1]: se})
                dm = bld.net(f'{cn}/dscan')
                bld.add(f'{cn}/scan', '$_MUX_', dict(S=se, B=si, A=d, Y=dm))
                d = dm
            if CLOCK_PIN in c['connections']:
                meta['clocks'].add(json.dumps(c['connections'][CLOCK_PIN][0]))
            init = 0
            if rp: init = 0
            if sp and not rp: init = 1
            for pin, act in ((rp, 0), (sp, 0)):
                if pin:
                    rn = bit(c, pin, cn)
                    info['inputs'][pin] = rn
                    r = meta['resets'].setdefault(json.dumps(rn), dict(net=rn, active=act, cells=[]))
                    r['cells'].append(cn)
            if reset_mode == 'sync':
                if rp:
                    dn = bld.net(f'{cn}/dclr')
                    bld.add(f'{cn}/clr', '$_AND_', dict(A=bit(c, rp, cn), B=d, Y=dn)); d = dn
                if sp:
                    ns = bld.net(f'{cn}/nset')
                    bld.add(f'{cn}/setn', '$_NOT_', dict(A=bit(c, sp, cn), Y=ns))
                    dn = bld.net(f'{cn}/dset')
                    bld.add(f'{cn}/set', '$_OR_', dict(A=ns, B=d, Y=dn)); d = dn
            q = c['connections'].get('Q', [None])[0] if c['connections'].get('Q') else None
            qn = c['connections'].get('QN', [None])[0] if c['connections'].get('QN') else None
            if q is None:
                q = bld.net(f'{cn}/q')
            bld.add(f'{cn}/ff', '$_DFF_P_', dict(C=bld.net(f'{cn}/clk'), D=d, Q=q))
            info['outputs']['Q'] = q
            meta['sites'][q] = dict(cell=cn, type=t, pin='Q', kind='flop')
            if qn is not None:
                bld.add(f'{cn}/qn', '$_NOT_', dict(A=q, Y=qn))
                info['outputs']['QN'] = qn
                meta['sites'][qn] = dict(cell=cn, type=t, pin='QN', kind='flop_qn')
            iv = flop_init.get(cn, init)
            meta['flops'][cn] = dict(type=t, q=q, qn=qn, init=iv, d=info['inputs'][dp],
                                     reset_pin=rp, set_pin=sp, scan=bool(scan))
        else:
            if t in TRISTATE:
                if not allow_tristate:
                    raise UnsupportedCell(f'{cn}: tristate cell {t} (enable would be ignored); pass allow_tristate=True')
                meta['tristate'].append(cn)
            if t not in funcs:
                raise UnsupportedCell(f'cell {cn} has type {t}: no combinational function in the SYNFI cell library')
            if t not in verified:
                verify_cells(lib, [t]); verified.add(t)
            outs = [p for p, dr in dirs.items() if dr == 'output']
            for p, dr in dirs.items():
                if dr == 'input':
                    info['inputs'][p] = bit(c, p, cn)
            for p in outs:
                if p not in funcs[t]:
                    raise UnsupportedCell(f'{cn}: {t} output {p} has no function')
                conn = c['connections'].get(p) or []
                if not conn or not isinstance(conn[0], int):
                    continue                                    # unconnected output
                prims = to_prims(funcs[t][p][1])
                ctr = [len([x for x in bld.cells if x.startswith(cn + '/')])]
                pinnet = {}
                for v in tree_vars(funcs[t][p][1]):
                    if v not in info['inputs']:
                        raise AdapterError(f'{cn}: function pin {v} not connected')
                    pinnet[v] = info['inputs'][v]
                _emit(bld, f'{cn}/{p}', prims, pinnet, conn[0], ctr)
                info['outputs'][p] = conn[0]
                meta['sites'][conn[0]] = dict(cell=cn, type=t, pin=p, kind='cell')
        info['prims'] = sorted(set(bld.cells) - before)
        meta['cells'][cn] = info
    nets = dict(m['netnames'])
    init_bits = {}
    for cn, f in meta['flops'].items():
        init_bits[f['q']] = f['init']
    newnames = {}
    for b, hint in bld.internal.items():
        newnames['$gs$' + hint] = dict(hide_name=1, bits=[b], attributes={})
    # flop init values as Yosys 'init' attributes on a dedicated netname per flop Q (engine reads 'init')
    for q, v in init_bits.items():
        newnames[f'$gs$init${q}'] = dict(hide_name=1, bits=[q], attributes=dict(init=str(v)))
    clean = {}
    for n, x in nets.items():
        a = {k: v for k, v in x.get('attributes', {}).items() if k != 'init'}
        clean[n] = dict(hide_name=x.get('hide_name', 0), bits=x['bits'], attributes=a)
    clean.update(newnames)
    newmod = dict(attributes=dict(top='1', glitchsat_adapter='nangate45'), ports=m['ports'], cells=bld.cells,
                  netnames=clean)
    meta['clocks'] = sorted(meta['clocks'])
    meta['resets'] = list(meta['resets'].values())
    meta['prim_count'] = len(bld.cells)
    meta['cell_count'] = len(meta['cells'])
    return dict(creator='glitchsat_real.nangate (from ' + str(doc.get('creator')) + ')', modules={top: newmod}), meta


def convert_file(path, top, out_json=None, out_meta=None, **kw):
    with open(path) as f:
        doc = json.load(f)
    nd, meta = convert(doc, top, **kw)
    if out_json:
        with open(out_json, 'w') as f:
            json.dump(nd, f)
    if out_meta:
        mm = dict(meta)
        mm['sites'] = {str(k): v for k, v in meta['sites'].items()}
        with open(out_meta, 'w') as f:
            json.dump(mm, f, indent=1)
    return nd, meta
