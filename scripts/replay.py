#!/usr/bin/env python3
"""Generate an iverilog replay testbench (and faulted gate-level netlist) FROM a glitchsat result JSON, run it, emit VCD.
Nothing is hand-written per attack: the netlist is re-emitted from the same Yosys JSON, the fault list and attacker input
come from the solver output. Fault-free control run is performed with the same bench.
Usage: replay.py <result.json> [--outdir tb/generated]"""
import json, os, re, subprocess, sys, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glitchsat as g
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def emit(nl, faults, in_ports, out_ports, N):
    """gate-level Verilog; fault list = [(cycle, net_id)] applied as XOR on that net during that cycle."""
    fs = {}
    for t, b in faults: fs.setdefault(b, []).append(t)
    L = [f"module dut_f(input clk, input run_faults, {', '.join(f'input [{len(v)-1}:0] {p}' for p, v in in_ports.items())}, "
         f"{', '.join(f'output [{len(v)-1}:0] {p}' for p, v in out_ports.items())});", "  integer cyc = 0;",
         "  always @(posedge clk) cyc <= cyc + 1;"]
    def nm(b):
        if b == '0' or b == 'x': return "1'b0"
        if b == '1': return "1'b1"
        for p, v in in_ports.items():
            if b in v: return f"{p}[{v.index(b)}]"
        return f"n{b}"
    def fx(b):
        if b not in fs: return None
        return '(' + ' | '.join(f'(run_faults && cyc=={t})' for t in fs[b]) + ')'
    nets = set()
    for cn, d, q in nl.dffs: nets.add(q)
    nets |= set(nl.drivers)
    for b in sorted(nets): L.append(f"  wire n{b};")
    for b in sorted(nets): L.append(f"  wire r{b};")
    for cn, d, q in nl.dffs:
        L.append(f"  reg s{q} = 1'b{int(nl.init[q])}; assign r{q} = s{q};")
        L.append(f"  always @(posedge clk) s{q} <= {nm(d)};")
    for b, (cn, ty, con) in nl.drivers.items():
        a = lambda p: nm(con[p][0])
        e = {'$_AND_': lambda: f"{a('A')} & {a('B')}", '$_OR_': lambda: f"{a('A')} | {a('B')}", '$_XOR_': lambda: f"{a('A')} ^ {a('B')}",
             '$_NOT_': lambda: f"~{a('A')}", '$_MUX_': lambda: f"{a('S')} ? {a('B')} : {a('A')}"}[ty]()
        L.append(f"  assign r{b} = {e};")
    for b in sorted(nets):
        f = fx(b); L.append(f"  assign n{b} = r{b}" + (f" ^ {f};" if f else ";"))
    for p, v in out_ports.items():
        L.append(f"  assign {p} = {{" + ', '.join(nm(b) for b in reversed(v)) + "};")
    L.append("endmodule")
    return '\n'.join(L)

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('result'); ap.add_argument('--outdir', default=os.path.join(ROOT, 'tb', 'generated'))
    ap.add_argument('--tag'); a = ap.parse_args()
    return replay(a.result, a.outdir, a.tag)

def replay(result, outdir, tag=None):
    r = json.load(open(result))
    assert r['verdict'] == 'ATTACK_FOUND', 'replay needs an ATTACK_FOUND result'
    nl = g.Netlist(os.path.join(ROOT, r['netlist_json']), r['top'])
    N = r['bound']['cycles']
    tag = tag or os.path.splitext(os.path.basename(result))[0]
    os.makedirs(outdir, exist_ok=True)
    in_ports = {p: v['bits'] for p, v in nl.ports.items() if v['direction'] == 'input' and p != 'clk'}
    out_ports = {p: v['bits'] for p, v in nl.ports.items() if v['direction'] == 'output'}
    faults = [(f['cycle'], f['net_id']) for f in r['faults']]
    gv = re.search(r"== 0x([0-9A-Fa-f]+)", r['bound']['goal']); goal = int(gv.group(1), 16); gout = r['bound']['goal'].split()[0]
    ains = {p: v for p, v in r['attacker_input_raw'].items()}
    base = os.path.join(outdir, tag)
    open(base + '_dut.v', 'w').write(emit(nl, faults, in_ports, out_ports, N))
    outs = ', '.join(f'.{p}({p})' for p in out_ports)
    decl = '\n'.join(f"  reg [{len(v)-1}:0] {p} = {len(v)}'d{ains.get(p, 0)};" for p, v in in_ports.items())
    decl += '\n' + '\n'.join(f"  wire [{len(v)-1}:0] {p};" for p, v in out_ports.items())
    ins = ', '.join(f'.{p}({p})' for p in in_ports)
    tb = f"""// GENERATED by scripts/replay.py from {os.path.basename(result)} -- do not edit
module tb;
  reg clk = 0, run_faults = {{RUN}};
{decl}
  dut_f dut(.clk(clk), .run_faults(run_faults), {ins}, {outs});
  integer hit = -1, c;
  always #5 clk = ~clk;
  initial begin
    $dumpfile("{os.path.abspath(base)}_{{TAG}}.vcd"); $dumpvars(0, tb);
    for (c = 0; c < {N}; c = c + 1) begin
      #1; if ({gout} === {len(out_ports[gout])}'h{goal:X} && hit < 0) hit = c;   // sampled mid-cycle c (before posedge)
      @(posedge clk); #4;
    end
    $display("REPLAY run_faults=%0d goal_hit_cycle=%0d {gout}=%h input=%h", run_faults, hit, {gout}, {attack_in_name(ains)});
    $finish;
  end
endmodule
"""
    res = {}
    for tagx, run in (('faulted', 1), ('faultfree', 0)):
        src = tb.replace('{RUN}', str(run)).replace('{TAG}', tagx)
        tbf = f"{base}_tb_{tagx}.v"; open(tbf, 'w').write(src)
        exe = f"{base}_{tagx}.vvp"
        subprocess.run(['iverilog', '-g2012', '-o', exe, tbf, base + '_dut.v'], check=True)
        o = subprocess.run(['vvp', exe], capture_output=True, text=True, check=True).stdout
        m = re.search(r'goal_hit_cycle=(-?\d+)', o)
        res[tagx] = dict(goal_hit_cycle=int(m.group(1)), raw=o.strip(), vcd=os.path.relpath(f"{base}_{tagx}.vcd", ROOT))
    res['agrees_with_solver'] = res['faulted']['goal_hit_cycle'] >= 0 and res['faultfree']['goal_hit_cycle'] < 0
    json.dump(res, open(base + '_replay.json', 'w'), indent=2)
    print(json.dumps(res, indent=1)); return res

def attack_in_name(ains): return list(ains)[0]
if __name__ == '__main__': main()
